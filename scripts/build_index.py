#!/usr/bin/env python3
"""Build the generated recipe indexes from the recipes' front matter.

Outputs (all generated, do not edit by hand):
  recipes/README.md      all recipes by section with status, language and evidence
  recipes/index.json     machine-readable list: id, title, section, lang, status, evidence, tools, path, dates, `when`
  recipes/BY-SYMPTOM.md  "find a recipe by what's wrong": the first paragraph of "## When" -> recipe, by section
  docs/CHANGELOG.md      recipes added / updated, grouped by the `added:` / `updated:` dates, newest first

Section READMEs (recipes/<section>/README.md) are written by hand; --check also verifies they are complete: every recipe
of the section has a row, the row's status matches the recipe's front matter, and no row links a missing recipe.

Usage: python3 scripts/build_index.py [--check] [repo_root]
Without flags it REWRITES all four files. With --check it does not write and fails naming every stale file and every
incomplete section README (for CI).
"""
import argparse
import json
import re
import sys
from pathlib import Path

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
SECTIONS = [
    ("idea", "Idea and script"), ("hooks", "Hooks"), ("voice", "Voice and TTS"), ("image", "Images and backdrops"),
    ("camera", "Camera"), ("transitions", "Editing and transitions"), ("sound", "Sound and SFX"), ("captions", "Captions"),
    ("assembly", "Assembly and engines"), ("qa", "QA of the finished video"), ("vertical", "Vertical from long"),
    ("face", "Face and character"), ("text", "Text and humanizer"), ("carousels", "Carousels and cards"),
    ("slides", "Slides"), ("agent", "Working with an agent"), ("publishing", "Publishing"),
    ("cta", "CTA and lead magnets"), ("analytics", "Analytics"), ("brand", "Brand"),
]


def meta(p):
    t = p.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", t, re.S)
    d = {}
    for line in (m.group(1).splitlines() if m else []):
        line = line.split(" #", 1)[0]
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            d[k.strip()] = v.strip().strip('"')
    return d


def section_files(root, key):
    return sorted(p for p in (root / "recipes" / key).glob("*.md") if p.name != "README.md")


def when_text(p):
    """First paragraph of the "## When" section on one line (list items joined with "; "); "" if there is none."""
    t = p.read_text(encoding="utf-8")
    m = re.search(r"^## When[ \t]*\n(.*?)(?=^## |\Z)", t, re.S | re.M)
    if not m:
        return ""
    para = m.group(1).strip().split("\n\n", 1)[0]
    lines = [x.strip() for x in para.splitlines() if x.strip()]
    if lines and all(x.startswith(("- ", "* ")) for x in lines):
        return "; ".join(x[2:].strip() for x in lines)
    return " ".join(lines)


def tools_list(v):
    v = (v or "").strip()
    if v.startswith("[") and v.endswith("]"):
        v = v[1:-1]
    return [x.strip().strip('"\'') for x in v.split(",") if x.strip()]


def records(root=DEFAULT_ROOT):
    """All recipes in SECTIONS order, then file name: the same set and order as recipes/README.md."""
    out = []
    for key, name in SECTIONS:
        for p in section_files(root, key):
            d = meta(p)
            out.append({
                "id": d.get("id") or p.stem, "title": d.get("title", p.stem), "section": key,
                "section_name": name, "lang": d.get("lang", ""), "status": d.get("status", ""),
                "evidence": d.get("evidence", ""), "tools": tools_list(d.get("tools")),
                "path": f"recipes/{key}/{p.name}", "added": d.get("added", ""),
                "updated": d.get("updated") or d.get("added", ""), "when": when_text(p),
            })
    return out


def build_json(root=DEFAULT_ROOT):
    keys = ["id", "title", "section", "lang", "status", "evidence", "tools", "path", "added", "updated", "when"]
    items = [{k: r[k] for k in keys} for r in records(root)]
    return json.dumps(items, ensure_ascii=False, indent=2) + "\n"


def build_symptoms(root=DEFAULT_ROOT):
    out = ["# Find a recipe by what's wrong", "",
           "Generated by `scripts/build_index.py` from the first paragraph of each recipe's \"## When\", "
           "do not edit by hand. Each line: the symptom, then the recipe and its status. "
           "Full table: [README.md](README.md), machine-readable: [index.json](index.json).", ""]
    section = None
    for r in records(root):
        if r["section"] != section:
            if section is not None:
                out.append("")
            section = r["section"]
            out += [f"## {r['section_name']}", ""]
        rel = r["path"][len("recipes/"):]
        when = r["when"] or '(no "When" section)'
        out.append(f"- {when} → [{r['title']}]({rel}) · {r['status']}")
    return "\n".join(out) + "\n"


def build_changelog(root=DEFAULT_ROOT):
    by_date = {}
    for r in records(root):
        if r["added"]:
            by_date.setdefault(r["added"], {"Added": [], "Updated": []})["Added"].append(r)
        if r["updated"] and r["updated"] != r["added"]:
            by_date.setdefault(r["updated"], {"Added": [], "Updated": []})["Updated"].append(r)
    out = ["# Changelog", "",
           "Generated by `scripts/build_index.py` from the recipes' front matter (`added:` and `updated:`), "
           "do not edit by hand. Newest first; \"Updated\" lists recipes whose `updated` differs from `added`.", ""]
    for date in sorted(by_date, reverse=True):
        out += [f"## {date}", ""]
        for kind in ("Added", "Updated"):
            rows = sorted(by_date[date][kind], key=lambda r: (r["section"], r["id"]))
            if not rows:
                continue
            out += [f"### {kind}", ""]
            # the changelog lives in docs/, so root-relative recipe paths get ../
            out += [f"- [{r['title']}](../{r['path']}) ({r['section']}, {r['status']})" for r in rows]
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def build(root=DEFAULT_ROOT):
    out = ["# Recipes", "",
           "Instructions for AI agents. Generated by `scripts/build_index.py`, do not edit by hand. "
           "The \"why\" behind each recipe is in the textbook: [learn/](../learn/). "
           "Add a recipe: [CONTRIBUTING](../CONTRIBUTING.md), template: [templates/recipe.md](../templates/recipe.md). "
           "Find a recipe by symptom: [BY-SYMPTOM.md](BY-SYMPTOM.md); machine-readable list: [index.json](index.json).", ""]
    total = proven = 0
    body = []
    for key, name in SECTIONS:
        files = section_files(root, key)
        if not files:
            continue
        body += [f"## {name}", "", f"Section index: [{key}/README.md]({key}/README.md)", "", "| Recipe | Status | Lang | Evidence |", "|---|---|---|---|"]
        for p in files:
            d = meta(p)
            total += 1
            proven += d.get("status") == "proven"
            body.append(f"| [{d.get('title', p.stem)}]({key}/{p.name}) | {d.get('status', '')} | {d.get('lang', '')} | {d.get('evidence', '')} |")
        body.append("")
    out += [f"Total {total}, proven {proven}.", ""] + body
    return "\n".join(out)


SECTION_ROW = re.compile(r"^\|\s*\[[^\]]*\]\(([^)#\s]+\.md)\)\s*\|\s*([^|]*?)\s*\|", re.M)


def section_readme_problems(root=DEFAULT_ROOT):
    """Hand-written section READMEs vs the recipe files: missing rows, wrong status, rows for missing recipes."""
    problems = []
    for key, _ in SECTIONS:
        files = section_files(root, key)
        if not files:
            continue
        readme = root / "recipes" / key / "README.md"
        rel = f"recipes/{key}/README.md"
        if not readme.exists():
            problems.append(f"{rel} is missing")
            continue
        rows = {m.group(1): m.group(2) for m in SECTION_ROW.finditer(readme.read_text(encoding="utf-8"))}
        for p in files:
            status = meta(p).get("status", "")
            if p.name not in rows:
                problems.append(f"{rel}: no row for {p.name}")
            elif rows[p.name] != status:
                problems.append(f"{rel}: {p.name} listed as '{rows[p.name]}', front matter says '{status}'")
        for name in rows:
            if not (root / "recipes" / key / name).exists():
                problems.append(f"{rel}: row links missing recipe {name}")
    return problems


def outputs(root):
    """Relative path -> generated text, in a fixed order."""
    return {
        "recipes/README.md": build(root),
        "recipes/index.json": build_json(root),
        "recipes/BY-SYMPTOM.md": build_symptoms(root),
        "docs/CHANGELOG.md": build_changelog(root),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build recipes/README.md, recipes/index.json, recipes/BY-SYMPTOM.md and "
                                             "docs/CHANGELOG.md from the recipes' front matter (rewrites them unless --check).")
    ap.add_argument("root", nargs="?", type=Path, default=DEFAULT_ROOT, help="repository root (default: the parent of scripts/)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 naming every stale generated file")
    a = ap.parse_args(argv)
    root = a.root.resolve()
    if not (root / "recipes").is_dir():
        print(f"{root}: no recipes/ folder")
        return 1
    gen = outputs(root)
    if a.check:
        stale = [rel for rel, text in gen.items()
                 if not (root / rel).exists() or (root / rel).read_text(encoding="utf-8") != text]
        for rel in stale:
            print(f"{rel} is stale: run python3 scripts/build_index.py")
        problems = section_readme_problems(root)
        for msg in problems:
            print(f"{msg} (section READMEs are edited by hand)")
        if stale or problems:
            return 1
        print("index is fresh (" + ", ".join(gen) + ")")
        return 0
    for rel, text in gen.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text, encoding="utf-8")
    print(gen["recipes/README.md"].splitlines()[4])
    print("wrote " + ", ".join(gen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
